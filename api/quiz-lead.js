// Vercel Node serverless function: receives the answers from /get-started
// (the pre-booking quiz) and emails them to Haider so he can build a
// tailored demo before the call. Deliberately email-only: it does NOT write
// to the inbound_leads CRM table, because rows there with status
// 'nurturing' are picked up by api/cron/process-nurture.js and texted.
//
// Requires RESEND_API_KEY (and the a2h.info domain verified in Resend).
// Spam defense is the same as api/mockup-request.js: honeypot, self-hosted
// captcha + fill-time check, email syntax/disposable/MX validation.

const {
  honeypotTripped,
  isValidEmailSyntax,
  isDisposableEmail,
  verifyCaptcha,
  domainAcceptsMail,
  looksAutoGenerated,
  MIN_FILL_TIME_MS,
} = require('./_lib/spam-guard');

const NOTIFY_TO = 'hhuss786512tx@gmail.com';
const FROM_ADDRESS = 'A2H <hello@a2h.info>';

const escapeHtml = (str) =>
  String(str).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const nl2br = (s) => escapeHtml(s).replace(/\n/g, '<br>');
const clip = (v, n) => String(v || '').trim().slice(0, n);

module.exports = async function handler(req, res) {
  if (req.method !== 'POST') {
    res.status(405).json({ error: 'method not allowed' });
    return;
  }

  let body = req.body;
  if (typeof body === 'string') {
    try { body = JSON.parse(body); } catch { body = {}; }
  }
  body = body || {};

  if (honeypotTripped(body)) {
    res.status(200).json({ success: true });
    return;
  }

  const name = clip(body.name, 200);
  const business = clip(body.business, 200);
  const email = clip(body.email, 200);
  const phone = clip(body.phone, 60);
  const niche = clip(body.niche, 150);
  const why = (Array.isArray(body.why) ? body.why : []).slice(0, 8).map((w) => clip(w, 120)).filter(Boolean);
  const whyNote = clip(body.why_note, 1000);
  const budget = clip(body.budget, 60);
  const timeline = clip(body.timeline, 60);
  const siteUrl = clip(body.site_url, 200);
  const utmSource = clip(body.utm_source, 100);
  const utmCampaign = clip(body.utm_campaign, 100);

  if (!name || !business || !email) {
    res.status(400).json({ error: 'name, business, and email are required' });
    return;
  }
  if (!isValidEmailSyntax(email)) {
    res.status(400).json({ error: 'invalid_email' });
    return;
  }
  if (isDisposableEmail(email)) {
    res.status(400).json({ error: 'disposable_email' });
    return;
  }

  if (process.env.CAPTCHA_SECRET) {
    if (!verifyCaptcha(body.captcha_token, body.captcha_answer)) {
      res.status(400).json({ error: 'captcha_failed' });
      return;
    }
    const elapsed = Number(body.elapsed_ms);
    if (Number.isFinite(elapsed) && elapsed < MIN_FILL_TIME_MS) {
      res.status(400).json({ error: 'too_fast' });
      return;
    }
  }

  const mailOk = await domainAcceptsMail(String(email).split('@')[1] || '');
  if (mailOk === false) {
    res.status(400).json({ error: 'email_domain_unreachable' });
    return;
  }

  const spamFlagged = looksAutoGenerated(business);

  const apiKey = process.env.RESEND_API_KEY;
  if (!apiKey) {
    res.status(200).json({ success: false, reason: 'not_configured' });
    return;
  }

  const source = utmSource || 'organic/direct';
  const html = `
    <h2>${spamFlagged ? '🚩 Possibly spam — ' : ''}New quiz lead: ${escapeHtml(business)}</h2>
    <p><strong>Source:</strong> ${escapeHtml(source)}${utmCampaign ? ` (${escapeHtml(utmCampaign)})` : ''}</p>
    <p><strong>Name:</strong> ${escapeHtml(name)}</p>
    <p><strong>Business:</strong> ${escapeHtml(business)}</p>
    <p><strong>Email:</strong> ${escapeHtml(email)}</p>
    <p><strong>Phone:</strong> ${escapeHtml(phone) || '—'}</p>
    <hr>
    <p><strong>Industry:</strong> ${escapeHtml(niche) || '—'}</p>
    <p><strong>Why a new site:</strong> ${why.length ? why.map(escapeHtml).join('; ') : '—'}</p>
    <p><strong>Notes:</strong><br>${whyNote ? nl2br(whyNote) : '—'}</p>
    <p><strong>Budget:</strong> ${escapeHtml(budget) || '—'}</p>
    <p><strong>Timeline:</strong> ${escapeHtml(timeline) || '—'}</p>
    <p><strong>Current site:</strong> ${siteUrl ? escapeHtml(siteUrl) : '—'}</p>
    <p>They were sent to the Calendly page next. Build the demo from these answers before the call.</p>
  `;

  try {
    const r = await fetch('https://api.resend.com/emails', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${apiKey}` },
      body: JSON.stringify({
        from: FROM_ADDRESS,
        to: NOTIFY_TO,
        reply_to: email,
        subject: `${spamFlagged ? '🚩 ' : ''}Quiz lead — ${business} (${niche || 'industry n/a'})`,
        html,
      }),
    });
    if (!r.ok) {
      const errText = await r.text().catch(() => '');
      res.status(200).json({ success: false, reason: 'notify_failed', detail: errText.slice(0, 300) });
      return;
    }
    res.status(200).json({ success: true });
  } catch (err) {
    res.status(200).json({ success: false, reason: 'exception', detail: String(err).slice(0, 300) });
  }
};
